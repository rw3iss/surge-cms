/**
 * Generate the in-admin API reference (`/admin/help/api`) from the route
 * manifest.
 *
 * Inputs (all generated or checked elsewhere, so this page can't drift):
 *   docs/api-manifest.json              — every route (npm run docs:api)
 *   cms-client/src/modules/coverage.ts  — which routes the SDK covers
 *   the SDK module reference            — WHICH method calls each route
 *
 * Run:  npm run docs:api-ref -w @sitesurge/admin   (root `npm run docs:api`
 *       runs it after regenerating the manifest + the SDK reference)
 * Guard: services/help/apiReference.test.ts fails when the committed output
 *        is stale.
 */
import { readFileSync, writeFileSync, } from 'node:fs';
import { resolve, } from 'node:path';
import { INTENTIONALLY_UNEXPOSED, ROUTE_COVERAGE, } from '../../cms-client/src/modules/coverage';
import { buildSdkModuleDocs, } from './generate-sdk-modules';

const MANIFEST_FILE = resolve(import.meta.dirname, '../../../docs/api-manifest.json',);
const OUT_FILE = resolve(import.meta.dirname, '../src/services/help/apiReference.generated.ts',);

interface Field { name: string; type: string; required: boolean; description?: string; }

interface ManifestRoute {
    method: string;
    path: string;
    absolutePath: string;
    auth: string;
    summary: string;
    raw?: boolean;
    input?: { params?: Field[]; query?: Field[]; body?: Field[]; };
}

interface ManifestModule {
    module: string;
    mountPath: string;
    feature?: string;
    routes: ManifestRoute[];
}

export interface ApiRouteDoc extends ManifestRoute {
    /** SDK methods calling this route, e.g. `cms.posts.list`. */
    sdk: string[];
    /** `method` (named SDK methods) | `covered` (in the coverage map, method
     *  not resolved) | `unexposed` (deliberately not in the SDK) | `none`. */
    sdkStatus: 'method' | 'covered' | 'unexposed' | 'none';
}

export interface ApiModuleDoc {
    module: string;
    mountPath: string;
    feature?: string;
    routes: ApiRouteDoc[];
}

export function buildApiReference(): ApiModuleDoc[] {
    const manifest = JSON.parse(readFileSync(MANIFEST_FILE, 'utf8',),) as { modules: ManifestModule[]; };

    // route → SDK methods, inverted from the SDK reference.
    const byRoute = new Map<string, string[]>();
    for (const mod of buildSdkModuleDocs()) {
        for (const m of mod.methods) {
            for (const r of m.routes) {
                const list = byRoute.get(r,) ?? [];
                list.push(`cms.${mod.namespace}.${m.name}`,);
                byRoute.set(r, list,);
            }
        }
    }
    const covered = new Set(ROUTE_COVERAGE,);
    const unexposed = new Set(INTENTIONALLY_UNEXPOSED,);

    return [...manifest.modules,]
        .sort((a, b,) => a.module.localeCompare(b.module,))
        .map((mod,) => ({
            module: mod.module,
            mountPath: mod.mountPath,
            ...(mod.feature ? { feature: mod.feature, } : {}),
            routes: mod.routes.map((r,) => {
                const key = `${r.method} ${r.absolutePath}`;
                const sdk = (byRoute.get(key,) ?? []).sort();
                const sdkStatus: ApiRouteDoc['sdkStatus'] = sdk.length
                    ? 'method'
                    : covered.has(key,) ? 'covered' : unexposed.has(key,) ? 'unexposed' : 'none';
                return { ...r, sdk, sdkStatus, };
            },),
        }));
}

export function renderFile(mods: ApiModuleDoc[],): string {
    const routes = mods.reduce((n, m,) => n + m.routes.length, 0,);
    return `// GENERATED by packages/cms/scripts/generate-api-reference.ts — DO NOT EDIT.
//
// The API reference shown at /admin/help/api: every route in
// docs/api-manifest.json, with the SDK method(s) that call it.
// Regenerate with: npm run docs:api   (root — refreshes the manifest first)

export interface ApiFieldDoc {
    name: string;
    type: string;
    required: boolean;
    description?: string;
}

export interface ApiRouteDoc {
    method: string;
    path: string;
    absolutePath: string;
    auth: string;
    summary: string;
    raw?: boolean;
    input?: { params?: ApiFieldDoc[]; query?: ApiFieldDoc[]; body?: ApiFieldDoc[]; };
    sdk: string[];
    sdkStatus: 'method' | 'covered' | 'unexposed' | 'none';
}

export interface ApiModuleDoc {
    module: string;
    mountPath: string;
    feature?: string;
    routes: ApiRouteDoc[];
}

export const API_MODULES: ApiModuleDoc[] = ${JSON.stringify(mods, null, 4,)};

export const API_MODULE_COUNT = ${mods.length};
export const API_ROUTE_COUNT = ${routes};
`;
}

if (process.argv[1]?.endsWith('generate-api-reference.ts',)) {
    const mods = buildApiReference();
    writeFileSync(OUT_FILE, renderFile(mods,),);
    const routes = mods.flatMap((m,) => m.routes);
    console.log(
        `Wrote ${OUT_FILE}\n  ${mods.length} modules, ${routes.length} routes `
            + `(${routes.filter((r,) => r.sdkStatus === 'method').length} with a named SDK method).`,
    );
}
